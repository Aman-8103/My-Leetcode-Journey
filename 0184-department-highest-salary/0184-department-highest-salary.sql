WITH RANKED_SALARY AS(
    SELECT D.NAME AS DEPARTMENT,
    E.NAME AS EMPLOYEE,
    E.SALARY AS SALARY,
    DENSE_RANK() OVER(PARTITION BY E.DEPARTMENTID ORDER BY E.SALARY DESC) AS RNK
    FROM EMPLOYEE AS E
    JOIN DEPARTMENT AS D
    ON E.DEPARTMENTID=D.ID
)
SELECT DEPARTMENT,EMPLOYEE, SALARY
FROM RANKED_SALARY
WHERE RNK=1;