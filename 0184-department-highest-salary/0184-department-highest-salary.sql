SELECT D.NAME AS Department,
        E.NAME AS Employee,
        E.SALARY AS Salary
FROM EMPLOYEE AS E
JOIN DEPARTMENT AS D
ON E.DEPARTMENTID=D.ID
WHERE (E.DEPARTMENTID,E.SALARY) IN(
    SELECT DEPARTMENTID,MAX(SALARY) FROM EMPLOYEE
    GROUP BY DEPARTMENTID
);
